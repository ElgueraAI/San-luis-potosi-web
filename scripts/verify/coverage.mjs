// Writes docs/data-coverage.md and docs/media-coverage.md from the entity
// layer and the production media set. Numbers in these docs come only from here.
//   node scripts/verify/coverage.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const R = (...p) => path.join(root, ...p);
const J = (p) => JSON.parse(fs.readFileSync(R(p), 'utf8'));
const E = (c) => J(`research/entities/${c}/index.json`).records;
const media = J('src/data/generated/media.json').assets;
const REG = { altiplano: 'Altiplano', centro: 'Centro', 'zona-media': 'Zona Media', huasteca: 'Huasteca' };

const munis = E('municipalities');
const attractions = E('attractions');
const dests = attractions.filter((a) => a.entity_type === 'destination');
const arch = E('archaeology');
const museums = E('museums');
const venues = E('cultural-venues');
const events = E('events');
const lodging = E('lodging');
const food = E('food-drink');
const manifest = J('research/media-registry/destination-asset-manifest.json').destinations;

// media status of an asset id
const status = (id) => {
  if (!id || !media[id]) return null;
  const m = media[id];
  return m.tier === 'review-thumb' || Math.max(m.width, m.height) < 1400 ? 'LOW_RESOLUTION' : 'READY';
};
const destImage = (d) => { const s = manifest[d.id]?.slots ?? {}; return [s.hero_desktop, s.card, ...(d.image_ids ?? [])].find((x) => x && media[x]) ?? null; };
const pending = new Set(J('research/generated/maplibre-pending.json').places.map((p) => p.place_id));

// experiences and event images are defined in site code: read their ids
const expSrc = fs.readFileSync(R('src/data/experiences.ts'), 'utf8');
const experiences = [...expSrc.matchAll(/\{ id: '([ACHM]\d\d)', title: '([^']+)', interest: '[^']+', image: '([^']+)' \}/g)].map((m) => ({ id: m[1], title: m[2], image: m[3] }));
const evSrc = fs.readFileSync(R('src/data/eventsText.ts'), 'utf8');
const evImg = Object.fromEntries([...evSrc.matchAll(/'([\w-]+)': \{ id: '([\w-]+)'/g)].map((m) => [m[1], m[2]]));

const rows = (head, body) => [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...body.map((r) => `| ${r.join(' | ')} |`)].join('\n');
const count = (list, f) => list.filter(f).length;

// ---------------------------------------------------------------- media ----
const muniRows = munis.map((m) => {
  const ds = dests.filter((d) => d.municipality_id === m.id);
  const img = ds.map(destImage).find(Boolean);
  const st = img ? status(img) : ds.length ? 'NEEDS_MANUAL_ASSET' : 'NO_SAFE_IMAGE_FOUND';
  return [m.canonical_name, REG[m.region] ?? 'Por confirmar', ds.length, img ? `\`${img}\`` : '—', st];
});
const destRows = dests.map((d) => { const img = destImage(d); return [d.id, d.canonical_name, img ? `\`${img}\`` : '—', img ? status(img) : 'NEEDS_MANUAL_ASSET']; });
const expRows = experiences.map((x) => [x.title, x.id, `\`${x.image}\``, status(x.image) ?? 'NEEDS_REVIEW']);
const evRows = events.map((e) => [e.canonical_name, e.municipality ?? '—', evImg[e.id] ? `\`${evImg[e.id]}\`` : '—', evImg[e.id] ? status(evImg[e.id]) : 'NO_SAFE_IMAGE_FOUND']);
const archRows = arch.map((a) => { const img = a.related_entities.map((id) => dests.find((d) => d.id === id)).filter(Boolean).map(destImage).find(Boolean); return [a.canonical_name, a.access_status, img ? `\`${img}\`` : '—', img ? status(img) : 'NO_SAFE_IMAGE_FOUND']; });
const tally = (rs, col) => Object.entries(rs.reduce((a, r) => ((a[r[col]] = (a[r[col]] ?? 0) + 1), a), {})).map(([k, v]) => `${k} ${v}`).join(' · ');
const tiers = Object.values(media).reduce((a, m) => ((a[m.tier] = (a[m.tier] ?? 0) + 1), a), {});

const mediaMd = `# Media coverage

Generated by \`scripts/verify/coverage.mjs\` from \`research/entities\` and \`src/data/generated/media.json\` (${Object.keys(media).length} production images: ${Object.entries(tiers).map(([k, v]) => `${k} ${v}`).join(', ')}).

Statuses:
- **READY**: licensed image of at least 1,400 px.
- **LOW_RESOLUTION**: only a 960 px review rendition.
- **NEEDS_REVIEW**: candidate not yet reviewed.
- **NEEDS_MANUAL_ASSET**: the entity is researched but no licensed photo exists.
- **NO_SAFE_IMAGE_FOUND**: no free-licence photo of this subject was found; a contextual placeholder is shown, never an unrelated photo.

Museums, cultural venues, lodging and food establishments use no photograph by design. Their cards carry type, place and source instead, so they are not listed below.

## Municipalities (${munis.length})
${tally(muniRows, 4)}

${rows(['Municipio', 'Región', 'Destinos', 'Imagen', 'Estado'], muniRows)}

## Destinations (${dests.length})
${tally(destRows, 3)}

${rows(['ID', 'Destino', 'Imagen', 'Estado'], destRows)}

## Experiences (${experiences.length})
${rows(['Experiencia', 'Destino', 'Imagen', 'Estado'], expRows)}

## Events (${events.length})
${tally(evRows, 3)}

${rows(['Evento', 'Municipio', 'Imagen', 'Estado'], evRows)}

## Archaeology (${arch.length})
${rows(['Sitio', 'Acceso', 'Imagen', 'Estado'], archRows)}

## Museums (${museums.length}) and cultural venues (${venues.length})
All NO_SAFE_IMAGE_FOUND as entities (SIC publishes no photographs). Five museums researched as destinations (C05, C07, C08, M06, H08) carry their destination photo.

## Lodging (${lodging.length}) and food (${food.length})
No hero image by design (not a booking platform). Official Estadía listings have photos on the official site; they are not reused because no reuse licence is stated.
`;
fs.writeFileSync(R('docs/media-coverage.md'), mediaMd);

// ----------------------------------------------------------------- data ----
const byRegion = (list) => Object.keys(REG).map((r) => count(list, (x) => x.region === r));
const dataRows = [
  ['Municipalities', munis.length, ...byRegion(munis), `${count(munis, (m) => m.seat)} with INEGI seat · ${count(munis, (m) => m.population_2020)} with 2020 population`],
  ['Destinations (researched)', dests.length, ...byRegion(dests), `${count(dests, (d) => d.verification_status === 'verified')} verified descriptions · ${count(dests, (d) => d.latitude != null)} with a point · ${dests.filter((d) => pending.has(d.id)).length} deliberately unplotted`],
  ['Protected areas & declarations (SIC)', attractions.length - dests.length, ...byRegion(attractions.filter((a) => a.entity_type !== 'destination')), 'Natural monuments, ANP, sacred natural sites, heritage, cathedrals'],
  ['Archaeology', arch.length, ...byRegion(arch), `${count(arch, (a) => a.access_status === 'OPEN_TO_PUBLIC')} open (INAH) · ${count(arch, (a) => a.access_status !== 'OPEN_TO_PUBLIC')} documented, access unknown`],
  ['Museums (SIC)', museums.length, ...byRegion(museums), `${new Set(museums.map((m) => m.municipality_id)).size} municipalities · ${count(museums, (m) => m.latitude != null)} with point`],
  ['Cultural venues (SIC)', venues.length, ...byRegion(venues), Object.entries(venues.reduce((a, v) => ((a[v.subcategory] = (a[v.subcategory] ?? 0) + 1), a), {})).map(([k, v]) => `${k} ${v}`).join(' · ')],
  ['Events', events.length, ...byRegion(events), Object.entries(events.reduce((a, e) => ((a[e.date_status] = (a[e.date_status] ?? 0) + 1), a), {})).map(([k, v]) => `${k} ${v}`).join(' · ')],
  ['Lodging', lodging.length, ...byRegion(lodging), `${count(lodging, (l) => l.official_directory)} official (Estadía) · ${count(lodging, (l) => l.denue)} DENUE`],
  ['Food & drink (all researched)', food.length, ...byRegion(food), `${count(food, (f) => f.exposed)} shown on the site (official, cafés, producers, 6+ staff)`],
  ['Services', E('services').length, ...byRegion(E('services')), 'Travel agencies, tour organisers (DENUE) + SECTUR guide directory'],
  ['Mobility', E('mobility').length, ...byRegion(E('mobility')), 'Airports and bus stations (DENUE)'],
  ['Recreation', E('recreation').length, ...byRegion(E('recreation')), 'Balnearios, grottos (DENUE)'],
];
const muniCov = munis.map((m) => [m.canonical_name, REG[m.region] ?? '—', m.counts.destinations, m.counts.museums, m.counts.venues, m.counts.events, m.counts.lodging, m.counts.food, m.counts.protected_areas]);
const dataMd = `# Data coverage

Generated by \`scripts/verify/coverage.mjs\` from \`research/entities\` (built by \`research/scripts/entities/build-entities.mjs\`).

${rows(['Set', 'Records', 'Altiplano', 'Centro', 'Zona Media', 'Huasteca', 'Notes'], dataRows)}

Records without a region are municipalities or listings that the sources do not place in a region (for example, Villa de Pozos, created in 2024).

## By municipality
${rows(['Municipio', 'Región', 'Destinos', 'Museos', 'Recintos', 'Eventos', 'Hospedaje', 'Comida', 'ANP'], muniCov)}

Municipalities with no researched destination: ${munis.filter((m) => !m.counts.destinations).length} of ${munis.length}. Their pages use the short format: identity, map, what is recorded, neighbours and sources.
`;
fs.writeFileSync(R('docs/data-coverage.md'), dataMd);
console.log('wrote docs/media-coverage.md, docs/data-coverage.md');
console.log('municipality media:', tally(muniRows, 4));
console.log('destination media:', tally(destRows, 3));
console.log('event media:', tally(evRows, 3));
